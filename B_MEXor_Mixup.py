def xor_upto(n):
    if n%4==0:
        return n
    elif n%4==1:
        return 1
    elif n%4==2:
        return n+1
    else:
        return 0
t=int(input())
for _ in range(t):
    a,b=map(int,input().split())
    a_xor=xor_upto(a-1)
    if a_xor==b :
        print(a)
    elif (a_xor ^a)==b:
        print(a+2)
    else:
        print(a+1)