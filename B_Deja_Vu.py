t=int(input())
for _ in range(t):
    n,q=map(int,input().split())
    a=list(map(int,input().split()))
    x=list(map(int,input().split()))
    prev=31
    for i in range(q):
        if x[i]>=prev:
            continue
        val=2**x[i]
        for j in range(n):
            if a[j]%val==0:
                a[j]+=(val//2)
        prev=x[i]
    print(*a)