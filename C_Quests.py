t=int(input())
for _ in range(t):
    n,k=map(int,input().split())
    a=list(map(int,input().split()))
    b=list(map(int,input().split()))
    maxy,sumy,resy=00,00,00
    for i in range(min(n,k)):
        sumy+=a[i]
        maxy=max(maxy,b[i])
        resy=max(resy,sumy+(k-(i+1))*maxy)
    print(resy)