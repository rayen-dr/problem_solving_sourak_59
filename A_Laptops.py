n=int(input())
laptops=[]
for _ in range(n):
    a,b=map(int,input().split())
    laptops.append((a,b))
laptops.sort(key=lambda x:x[0])
for i in range(n-1):
    if laptops[i][1]>laptops[i+1][1]:
        print("Happy Alex")
        break
else:
    print("Poor Alex")