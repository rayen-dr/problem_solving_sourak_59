import math
t=int(input())
for _ in range(t):
    n=int(input())
    n-=1
    msb=int(math.log2(n))
    res=[]
    num=(1<<msb)-1
    while num>=0:
        res.append(num)
        num-=1
    num=(1<<msb)
    while num<=n:
        res.append(num)
        num+=1
    print(' '.join(map(str,res)))