def prefix(p):
    n=len(p)
    p_res=[0]*(n+1)
    for i in range(1,n+1):
        p_res[i]=p_res[i-1]+p[i-1]
    return p_res
n=int(input())
a=list(map(int,input().split()))
q=int(input())
prefixy=prefix(a)
for _ in range(q):
    x,y,m=map(int,input().split())
    kinda1=x+(prefixy[n]-x if prefixy[n]>=x else 0)
    kinda2=y+prefixy[m]
    print(min(kinda1,kinda2))