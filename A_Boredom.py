import sys
input=sys.stdin.read
data=list(map(int,input().split()))
n=data[0]
a=data[1:]
from collections import Counter
cnt=Counter(a)
max_val=max(a)
dp=[0]*(max_val+1)
dp[0]=0
dp[1]=cnt[1]*1
for i in range(2,max_val+1):
    dp[i]=max(dp[i-1],dp[i-2]+cnt[i]*i)
print(dp[max_val])