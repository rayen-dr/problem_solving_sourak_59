t = int(input())
for _ in range(t):
    n,k,b,s=map(int,input().split())
    minimum_s=k*b
    maximum_s=(k*b)+(k-1)*n
    if s<minimum_s or s>maximum_s:
        print("-1")
    else:
        ans=[0]*n
        ans[0]=minimum_s
        s-=minimum_s
        for i in range(n):
            add=min(k-1,s)
            ans[i]+=add
            s-=add
        print(' '.join(map(str, ans)))
