n=int(input())
matrix=[[0]*n for _ in range(n)]
matrix[0][0]=1
maxi=1
for i in range(n):
    for j in range(n):
        if i==0:
            matrix[i][j]=1
            continue
        matrix[i][j]=matrix[i-1][j]+matrix[i][j-1]
        maxi=max(maxi,matrix[i][j])
print(maxi)