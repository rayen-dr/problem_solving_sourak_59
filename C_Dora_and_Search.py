t=int(input())
for _ in range(t):
    n=int(input())
    a=list(map(int,input().split()))
    l,r=0,n-1
    mini,maxi=1,n
    while l<r:
        if a[l]==mini or a[l]==maxi:
            if a[l]==mini:
                mini+=1
            else:
                maxi-=1
            l+=1
            continue
        if a[r]==mini or a[r]==maxi:
            if a[r]==mini:
                mini+=1
            else:
                maxi-=1
            r-=1
            continue
        break
    if l<r:
        print(l+1,r+1)
    else:
        print(-1)