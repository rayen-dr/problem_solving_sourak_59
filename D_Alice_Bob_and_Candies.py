t = int(input())
for _ in range(t):
    n = int(input())
    a = list(map(int, input().split()))
    l, r = 0, n - 1
    suml, sumr = 0, 0
    cnt = 0
    ansl, ansr = 0, 0
    while l <= r:
        if cnt % 2 == 0:
            nsuml = 0
            while l <= r and nsuml <= sumr:
                nsuml += a[l]
                l += 1
            ansl += nsuml
            suml = nsuml
        else:
            nsumr = 0
            while l <= r and nsumr <= suml:
                nsumr += a[r]
                r -= 1
            ansr += nsumr
            sumr = nsumr
        cnt += 1
    print(cnt, ansl, ansr)