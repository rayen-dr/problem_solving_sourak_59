def regular_bracket_sequence(s):
    n=len(s)
    st=0
    max_len=0
    for i in range(len(s)):
        if s[i]=="(":
            st+=1 
        else: 
            if st>0:
                st-=1
                max_len+=1
    return 2*max_len

t=int(input())
for _ in range(t):
    n=int(input())
    s=input().strip()
    c=regular_bracket_sequence(s)
    print((n-c)//2)