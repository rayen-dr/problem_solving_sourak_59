t=int(input())
for _ in range(t):
    n=int(input())
    a=list(map(int,input().split()))
    ans=-float('inf')
    i=0
    j=0
    sumy=0
    while j<n:
        if sumy<0:
            sumy=0
            i=j
        if i<j:
            if(a[j]^a[j-1])%2!=0:
                sumy+=a[j]
            else:
                sumy=a[j]
                i=j
        else:
            sumy=a[j]
        ans=max(ans,sumy)
        j+=1
    print(ans)