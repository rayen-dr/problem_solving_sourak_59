def solve():
    n, c = map(int, input().split())
    a = list(map(int, input().split()))
    l, r = 1, 10**9
    while l <= r:
        mid = (l + r) // 2
        sumall = 0
        for x in a:
            sumall += (x + 2 * mid) * (x + 2 * mid)
            if sumall > c:
                break
        if sumall == c:
            print(mid)
            return
        elif sumall > c:
            r = mid - 1
        else:
            l = mid + 1
t = int(input())
for _ in range(t):
    solve()