def ceil_div(a,b):
    return(a+b-1)//b
t=int(input())
for _ in range(t):
    x,y,k=map(int,input().split())
    sticks_needed=k*y+k-1
    sticks_gained_per_trade=x-1
    trades=ceil_div(sticks_needed,sticks_gained_per_trade)
    trades+=k
    print(trades)