n,l=map(int,input().split())
a=list(map(int,input().split()))
a.sort()
if n==1:
    d=max(a[0],l-a[0])
else:
    max_gap=max(a[i+1]-a[i] for i in range(n-1))
    d=max(max_gap/2,a[0]-0,l-a[-1])
print(f"{d:.10f}")