t=int(input())
for _ in range(t):
    n=int(input())
    a=list(map(int,input().split()))
    nb_even,nb_odd=0,0
    for i in range(n):
        if not(a[i]%2==i%2):
            if i%2==0:
                nb_odd+=1
            else:
                nb_even+=1
    print(nb_odd if nb_even==nb_odd else -1)