def longest_common_substring(a, b):
    n,m=len(a),len(b)
    dp=[[0]*(m+1) for _ in range(n+1)]
    lcs=0
    for i in range(1,n+1):
        for j in range(1,m+1):
            if a[i-1]==b[j-1]:
                dp[i][j]=dp[i-1][j-1]+1
                lcs=max(lcs,dp[i][j])
    return lcs
 
t=int(input())
for _ in range(t):
    a=input()
    b=input()
    print(len(a)+len(b)-2*longest_common_substring(a,b))