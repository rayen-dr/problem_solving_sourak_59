from collections import Counter
t=int(input())
for _ in range(t):
    n,k=map(int,input().split())
    a=input()
    b=input()
    cnt_a=Counter(a)
    cnt_b=Counter(b)
    for i in range(n):
        if cnt_a[a[i]]%k==0 or a[i]==b[i]:
            print("Yes")
            break
    else:
        print("No")