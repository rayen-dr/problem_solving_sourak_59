def CutRibbon(a,b,c,n):
    res=1
    for x in range(n//a+1):
        for y in range(n//b+1):
            if (n-(a*x)-(b*y))%c==0 and (n-a*x-b*y)>=0:
                z=(n-a*x-b*y)//c
                res=max(res,x+y+z)
    print(res)
def main():
    n,a,b,c=map(int,input().split())
    CutRibbon(a,b,c,n)

if __name__=="__main__":
    main()