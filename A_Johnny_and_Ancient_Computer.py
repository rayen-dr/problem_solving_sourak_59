import math
t=int(input())
for _ in range(t):
    a,b=map(int,input().split())
    ra,rb=a,b
    while ra%2==0:
        ra//=2
    while rb%2==0:
        rb//=2
    if ra!=rb:
        print(-1)
    else:
        a//=ra
        b//=rb
        a=math.log2(a)
        b=math.log2(b)
        print(math.ceil(abs(a-b)/3.0))